document.getElementById('contact-form').addEventListener('submit', (event) => {
  event.preventDefault();
  const [name, email, message] = event.currentTarget.querySelectorAll('input, textarea');
  const language = document.documentElement.lang;
  const subject = language === 'et' ? `Päring ÄRI KORRAS: ${name.value}` : language === 'ru' ? `Запрос ÄRI KORRAS: ${name.value}` : `ÄRI KORRAS enquiry: ${name.value}`;
  const body = language === 'et'
    ? `Nimi: ${name.value}\nE-post: ${email.value}\n\nPäring:\n${message.value}`
    : language === 'ru'
      ? `Имя: ${name.value}\nЭлектронная почта: ${email.value}\n\nЗапрос:\n${message.value}`
      : `Name: ${name.value}\nEmail: ${email.value}\n\nEnquiry:\n${message.value}`;
  window.location.href = `mailto:info@arikorras.ee?subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(body)}`;
  document.getElementById('form-success').style.display = 'block';
});
